// ── Nav item definitions ─────────────────────────────────────────────────────

type NavItem = {
  to: string;
  label: string;
  icon: ReactNode;
  end?: boolean;
  roles?: string[];
  badge?: number;
};

const Sidebar = () => {
  const { user } = useAuth();
  const role = user?.role ?? '';

  const { data: unreadCount } = useGetData<{ count: number }, string, number>({
    queryKey: ['announcements', 'unread-count'],
    queryFn: getUnreadCount,
    transformFn: (d) => d.count,
    enabled: !!user,
  });

  const navItems: NavItem[] = [
    { to: '/', end: true,  label: 'Home',         icon: <IconHome /> },
    { to: '/announcements', label: 'Announcements', icon: <IconBell />, badge: unreadCount },
    { to: '/courses',       label: 'Courses',       icon: <IconBook /> },
    { to: '/schedule',      label: 'Calendar',      icon: <IconCalendar /> },
    { to: '/payments',      label: 'Payments',      icon: <IconCard /> },
    { to: '/timetable', roles: ['TEACHER','ADMIN'], label: 'Timetable',  icon: <IconGrid /> },
    { to: '/teacher',   roles: ['TEACHER','ADMIN'], label: 'Workspace',  icon: <IconUsers /> },
    { to: '/admin',     roles: ['ADMIN'],           label: 'Admin',      icon: <IconSettings /> },
  ];

  const visible = navItems.filter(i => !i.roles || i.roles.includes(role));

  return (
    <aside className="app-sidebar" aria-label="Main navigation">
      <nav>
        <ul className="sidebar-nav">
          {visible.map(({ to, end, label, icon, badge }) => (
            <li key={to}>
              <NavLink
                to={to}
                end={end}
                className={({ isActive }) =>
                  `sidebar-link${isActive ? ' sidebar-link--active' : ''}`
                }
              >
                <span className="sidebar-link__icon">{icon}</span>
                <span className="sidebar-link__label">{label}</span>
                {!!badge && badge > 0 && (
                  <span className="sidebar-link__badge" aria-label={`${badge} unread`}>
                    {badge}
                  </span>
                )}
              </NavLink>
            </li>
          ))}
        </ul>
      </nav>
    </aside>
  );
};

export default Sidebar;
